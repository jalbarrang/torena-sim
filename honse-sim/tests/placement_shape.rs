//! Placement-shape gate for the pre-race random activation samplers.
//!
//! mechanics § x_random: "Skills with random activation randomly pick a 10m
//! segment before a race starts." *Where* those segments land is fixed by the
//! documented procedures, so the shape can be compared against a measured
//! distribution even when the corpus comes from another implementation: both
//! read the same course geometry and the same build-independent rules.
//!
//! Every file in `tests/fixtures/placement/` is one course's corpus. They come
//! from two reference engines, both close to the game's own replay frames:
//!
//! - **Hakuraku** bulk snapshots (`umamoe-bulk`), millions of races over real
//!   lobby builds, served per CM course.
//! - **uma.moe** `/api/sim/monte-carlo` in `procs` mode, generated by
//!   `scripts/fetch-placement-fixtures.ts`.
//!
//! Neither is the game, so this is a cross-implementation shape check, not
//! ground truth. Each fixture records its own provenance.
//!
//! Tolerances follow the corpus: a bucket is allowed 5% or three binomial
//! standard errors of its own share, whichever is larger, and the equal-chance
//! per corner ratio gets the same treatment. A large corpus therefore gates
//! tightly and a small one cannot false-fail on its own sampling noise.
//!
//! Run with `--nocapture` to read the side-by-side buckets:
//!
//! ```text
//! cargo test -p honse-sim --test placement_shape -- --nocapture
//! ```

use std::collections::BTreeMap;
use std::path::PathBuf;

use honse_sim::shared_kernel::region::{Region, RegionList};
use honse_sim::shared_kernel::rng::Xoshiro256StarStar;
use honse_sim::skills::activation::ActivationSamplePolicy;
use serde::Deserialize;

/// Draws per case. Buckets sit far above a percent of Monte Carlo error, so the
/// gate measures the corpus rather than this sampler.
const DRAWS: usize = 1_000_000;
/// Realizations are binned in batches so a case never materialises the whole
/// sample as `Vec<Region>`s at once.
const BATCH: usize = 4_096;
/// Share of our sample a bucket may hold while the corpus saw nothing there.
/// Larger means we place mass where the reference never does (a wrong region);
/// smaller would trip on a corpus too small to sample that bucket.
const MISSING_SHARE: f64 = 0.002;
/// Floor for a bucket's allowed relative deviation, whatever the corpus size.
/// Above the sampler's own noise, and above the shape drift a live condition
/// adds (an `order_rate` gate tapers a phase-random tail by ~3%).
const TOLERANCE: f64 = 0.06;
/// Floor for the equal-chance-per-corner density ratio.
const CORNER_RATIO_TOLERANCE: f64 = 0.01;
/// How many binomial standard errors a corpus bucket may drift by.
const SIGMA: f64 = 3.0;

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Fixture {
    bucket_metres: f64,
    course_distance: f64,
    skills: Vec<Case>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Case {
    skill_id: String,
    condition: String,
    policy: String,
    /// Trigger regions the condition resolves to on this course, in metres.
    regions: Vec<[f64; 2]>,
    /// Bucket index -> first activations measured by the corpus.
    first_activations: BTreeMap<u32, u64>,
    #[serde(default)]
    total_first_activations: u64,
}

fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/placement")
}

fn policy_of(name: &str) -> ActivationSamplePolicy {
    match name {
        "allCornerRandom" => ActivationSamplePolicy::AllCornerRandom,
        "cornerRandom" => ActivationSamplePolicy::CornerRandom,
        "straightRandom" => ActivationSamplePolicy::StraightRandom,
        "random" => ActivationSamplePolicy::Random,
        other => panic!("unknown placement policy `{other}` in a fixture"),
    }
}

fn regions_of(case: &Case) -> RegionList {
    RegionList::from_vec(
        case.regions
            .iter()
            .map(|[start, end]| Region::new(*start, *end))
            .collect(),
    )
}

/// First-trigger histogram for the case, in buckets of `bucket_metres`.
fn sampled_histogram(case: &Case, fixture: &Fixture) -> Vec<u64> {
    let regions = regions_of(case);
    let policy = policy_of(&case.policy);
    let bucket_count = (fixture.course_distance / fixture.bucket_metres).ceil() as usize;
    let mut histogram = vec![0u64; bucket_count];
    let mut rng = Xoshiro256StarStar::from_u64_seed(0x0C21_2026);

    let mut drawn = 0;
    while drawn < DRAWS {
        let batch = BATCH.min(DRAWS - drawn);
        for realization in policy.sample(&regions, batch, &mut rng) {
            let Some(first) = realization.first() else {
                continue;
            };
            let index = first.start / fixture.bucket_metres;
            assert!(
                index >= 0.0,
                "{}: sampler produced a negative start",
                case.skill_id
            );
            histogram[index as usize] += 1;
        }
        drawn += batch;
    }
    histogram
}

/// Buckets fully inside `[start + bucket, end - bucket]`, with their count sum
/// and how many buckets contributed.
fn inner_counts(
    bucket_metres: f64,
    [start, end]: [f64; 2],
    count: impl Fn(u32) -> u64,
) -> (u64, u32) {
    let first = ((start + bucket_metres) / bucket_metres).ceil() as u32;
    let last = ((end - bucket_metres) / bucket_metres).floor() as u32;
    assert!(
        last > first,
        "{start}-{end}m is too short for a density comparison"
    );
    let sum: u64 = (first..last).map(&count).sum();
    (sum, last - first)
}

/// A bucket is comparable when it sits inside a region's start range
/// `[start, end - 10)` with a full bucket of margin at the region's start. The
/// reference records the position a tick after entering the window: a partial
/// sliver and a region's first bucket have no incoming smear to balance the
/// outgoing one, so both read low for reasons the sampler does not model.
fn comparable(bucket_metres: f64, bucket: u32, regions: &[[f64; 2]]) -> bool {
    let low = f64::from(bucket) * bucket_metres;
    let high = low + bucket_metres;
    regions
        .iter()
        .any(|[start, end]| low >= start + bucket_metres - 1e-9 && high <= end - 10.0 + 1e-9)
}

/// A corpus bucket may drift by 5% or three of its own standard errors.
fn bucket_tolerance(share: f64, total: u64) -> f64 {
    if share <= 0.0 || total == 0 {
        return f64::INFINITY;
    }
    let stderr = (share * (1.0 - share) / total as f64).sqrt();
    TOLERANCE.max(SIGMA * stderr / share)
}

/// Compare one case against the corpus and return every check that drifted.
fn compare(case: &Case, fixture: &Fixture) -> Vec<String> {
    let ours = sampled_histogram(case, fixture);
    let their_total = if case.total_first_activations > 0 {
        case.total_first_activations
    } else {
        case.first_activations.values().sum()
    };
    assert!(
        their_total > 0,
        "{}: fixture carries no activations",
        case.skill_id
    );

    assert!(
        ours.iter().any(|count| *count > 0),
        "{}: sampler produced nothing",
        case.skill_id
    );

    println!(
        "\n{}  {}  ({} · {} activations)",
        case.skill_id, case.condition, case.policy, their_total
    );
    let mut failures = Vec::new();
    for bucket in 0..ours.len() as u32 {
        if !comparable(fixture.bucket_metres, bucket, &case.regions) {
            continue;
        }
        let metres = f64::from(bucket) * fixture.bucket_metres;
        let our_share = ours[bucket as usize] as f64 / DRAWS as f64;
        let Some(&their_count) = case.first_activations.get(&bucket) else {
            // Gapped regions (straights) legitimately have no corpus buckets in
            // between. Only mass we put where the corpus saw none is a failure.
            if our_share > MISSING_SHARE {
                failures.push(format!(
                    "{}: {metres:.0}m holds {:.4} of our samples but none of the corpus's",
                    case.skill_id, our_share
                ));
            }
            continue;
        };
        let their_share = their_count as f64 / their_total as f64;
        let ratio = our_share / their_share;
        let allowed = bucket_tolerance(their_share, their_total);
        println!(
            "  {metres:>5.0}-{:>5.0}m  ours {:>7}  corpus {their_count:>8}  ratio {ratio:.3}  ±{allowed:.3}",
            metres + fixture.bucket_metres,
            ours[bucket as usize]
        );
        if (ratio - 1.0).abs() > allowed {
            failures.push(format!(
                "{}: {metres:.0}m share {our_share:.5} vs corpus {their_share:.5} (ratio {ratio:.3}, allowed ±{allowed:.3})",
                case.skill_id
            ));
        }
    }

    // `all_corner_random` gives every corner an equal chance regardless of length
    // (mechanics § all_corner_random step 2). Per-bucket tolerance cannot see that:
    // the 10 m window shrinking each corner's span nearly cancels a length-weighted
    // pick (density ratio 1.002 instead of 1.053 on a 1200 m course). The ratio of
    // the two corner plateaus can.
    if case.policy == "allCornerRandom" {
        if let [left, right] = case.regions[..] {
            let corpus = |bucket: u32| case.first_activations.get(&bucket).copied().unwrap_or(0);
            let (ours_left, ours_left_n) =
                inner_counts(fixture.bucket_metres, left, |b| ours[b as usize]);
            let (ours_right, ours_right_n) =
                inner_counts(fixture.bucket_metres, right, |b| ours[b as usize]);
            let (theirs_left, theirs_left_n) = inner_counts(fixture.bucket_metres, left, corpus);
            let (theirs_right, theirs_right_n) = inner_counts(fixture.bucket_metres, right, corpus);

            let ours_ratio = (ours_right as f64 / f64::from(ours_right_n))
                / (ours_left as f64 / f64::from(ours_left_n));
            let theirs_ratio = (theirs_right as f64 / f64::from(theirs_right_n))
                / (theirs_left as f64 / f64::from(theirs_left_n));
            let stderr =
                (1.0 / theirs_left.max(1) as f64 + 1.0 / theirs_right.max(1) as f64).sqrt();
            let allowed = CORNER_RATIO_TOLERANCE.max(SIGMA * stderr);
            println!(
                "  corner density ratio  ours {ours_ratio:.4}  corpus {theirs_ratio:.4}  ±{allowed:.3}  (equal chance per corner, not length-weighted)"
            );
            if (ours_ratio / theirs_ratio - 1.0).abs() > allowed {
                failures.push(format!(
                    "{}: corner density ratio {ours_ratio:.4} vs corpus {theirs_ratio:.4} (allowed ±{allowed:.3})",
                    case.skill_id
                ));
            }
        }
    }

    failures
}

/// The samplers must keep the documented shapes on every fixture course:
/// uniform inside a phase or straight, and an equal chance per corner (never
/// length-weighted) for `all_corner_random`.
#[test]
fn placement_shape_matches_reference_corpora() {
    let dir = fixture_dir();
    let mut paths: Vec<PathBuf> = std::fs::read_dir(&dir)
        .expect("the placement fixture directory")
        .map(|entry| entry.expect("dir entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "json"))
        .collect();
    paths.sort();
    assert!(
        !paths.is_empty(),
        "no placement fixtures in {}",
        dir.display()
    );

    let mut failures = Vec::new();
    for path in paths {
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .expect("a fixture file name");
        let text = std::fs::read_to_string(&path).expect("read the placement fixture");
        let fixture: Fixture =
            serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {name}: {e}"));
        println!("\n=== {name}");
        for case in &fixture.skills {
            failures.extend(compare(case, &fixture));
        }
    }

    assert!(
        failures.is_empty(),
        "placement shape drifted from the corpora:\n{}",
        failures.join("\n")
    );
}
